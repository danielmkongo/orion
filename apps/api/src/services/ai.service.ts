import { GoogleGenerativeAI } from '@google/generative-ai';
import { config } from '../config/index.js';

/* ── Gemini client (lazy) ──────────────────────────────────────────── */
let _genAI: GoogleGenerativeAI | null = null;
function getClient() {
  if (!config.geminiApiKey) throw new Error('Orion AI is not configured');
  if (!_genAI) _genAI = new GoogleGenerativeAI(config.geminiApiKey);
  return _genAI;
}

/* ── Sliding-window rate limiter (14 req/min, free tier = 15) ─────── */
class RateLimiter {
  private slots: number[] = [];
  private readonly limit: number;

  constructor(limit = 14) { this.limit = limit; }

  get waiting(): number { return Math.max(0, this.slots.length - this.limit + 1); }

  async claim(): Promise<void> {
    while (true) {
      const now = Date.now();
      this.slots = this.slots.filter(t => now - t < 60_000);
      if (this.slots.length < this.limit) {
        this.slots.push(now);
        return;
      }
      const sleepMs = this.slots[0] + 60_000 - now + 300;
      await new Promise(r => setTimeout(r, Math.max(300, sleepMs)));
    }
  }
}

export const rateLimiter = new RateLimiter(14); // Gemini free tier: 15 req/min

