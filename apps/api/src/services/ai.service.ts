/* ── Public types ──────────────────────────────────────────────────── */
export interface CodeGenRequest {
  deviceName: string;
  deviceApiKey: string;
  serialNumber: string;
  apiBase: string;
  apiHost: string;
  mqttBroker: string;
  tcpPort: number;
  udpPort: number;
  coapPort: number;
  protocol: string;
  hardware: string;
  hardwareLabel: string;
  fields: Array<{ key: string; unit?: string }>;
  config: Record<string, string | number>;
}

export interface ReportRequest {
  deviceName: string;
  fields: Array<{ key: string; values: number[]; unit?: string }>;
  periodLabel: string;
}

/* ── Shared prompt builder ─────────────────────────────────────────── */
function buildFirmwarePrompt(req: CodeGenRequest): string {
  const fieldList = req.fields.length
    ? req.fields.map(f => `  - ${f.key}${f.unit ? ` (${f.unit})` : ''}`).join('\n')
    : '  (no schema defined — use generic placeholder fields)';

  const cfgList = Object.entries(req.config)
    .map(([k, v]) => `  ${k}: ${v}`)
    .join('\n');

  return `
Generate complete firmware for the following device.

DEVICE_NAME: ${req.deviceName}
HARDWARE: ${req.hardwareLabel}
PROTOCOL: ${req.protocol.toUpperCase()}
ISO_DATE: ${new Date().toISOString().slice(0, 10)}

CREDENTIALS:
  DEVICE_API_KEY: ${req.deviceApiKey}
  DEVICE_SERIAL: ${req.serialNumber}

ENDPOINTS:
  API_BASE: ${req.apiBase}
  API_HOST: ${req.apiHost}
  MQTT_BROKER: ${req.mqttBroker}
  TCP_PORT: ${req.tcpPort}
  UDP_PORT: ${req.udpPort}
  COAP_PORT: ${req.coapPort}

DATA FIELDS (exact JSON keys to send):
${fieldList}

HARDWARE CONFIG:
${cfgList}

Produce a single complete source file. Use ONLY the ${req.protocol.toUpperCase()} protocol.
`.trim();
}

/* ── Service ───────────────────────────────────────────────────────── */
export const aiService = {

  isConfigured() {
    return !!config.geminiApiKey;
  },

  async generateFirmware(req: CodeGenRequest): Promise<string> {
    await rateLimiter.claim();
    const model = getClient().getGenerativeModel({
      model: 'gemini-2.0-flash',
      systemInstruction: CODEGEN_SYSTEM_PROMPT,
    });
    const result = await model.generateContent(buildFirmwarePrompt(req));
    let code = result.response.text().trim();
    code = code.replace(/^```[\w]*\n?/m, '').replace(/\n?```$/m, '').trim();
    return code;
  },

  async *generateFirmwareStream(
    req: CodeGenRequest,
    onWait?: (seconds: number) => void,
  ): AsyncGenerator<string> {
    const model = getClient().getGenerativeModel({
      model: 'gemini-2.0-flash',
      systemInstruction: CODEGEN_SYSTEM_PROMPT,
    });
    const prompt = buildFirmwarePrompt(req);

    const MAX_RETRIES = 3;
    for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
      try {
        await rateLimiter.claim();
        const result = await model.generateContentStream(prompt);
        for await (const chunk of result.stream) {
          const text = chunk.text();
          if (text) yield text;
        }
        return; // success
      } catch (err: any) {
        // GoogleGenerativeAIFetchError has .status; fall back to message scan
        const status: number =
          err?.status ??
          err?.response?.status ??
          (typeof err?.message === 'string' && /\b429\b/.test(err.message) ? 429 : 0);

        console.error(`[OrionAI] attempt ${attempt + 1} failed — status=${status} message=${err?.message}`);

        if (status === 429 && attempt < MAX_RETRIES) {
          const waitSeconds = 65;
          if (onWait) onWait(waitSeconds);
          await new Promise(r => setTimeout(r, waitSeconds * 1000));
          continue;
        }
        throw err;
      }
    }
  },

  async generateReport(req: ReportRequest): Promise<object> {
    await rateLimiter.claim();
    const model = getClient().getGenerativeModel({
      model: 'gemini-2.0-flash',
      systemInstruction: REPORT_SYSTEM_PROMPT,
    });

    const fieldSummaries = req.fields.map(f => {
      const vals = f.values;
      if (!vals.length) return `${f.key}: no data`;
      const mn = Math.min(...vals).toFixed(2);
      const mx = Math.max(...vals).toFixed(2);
      const avg = (vals.reduce((a, b) => a + b, 0) / vals.length).toFixed(2);
      return `${f.key}${f.unit ? ` (${f.unit})` : ''}: min=${mn} max=${mx} avg=${avg} samples=${vals.length}`;
    }).join('\n');

    const userPrompt = `Device: ${req.deviceName}\nPeriod: ${req.periodLabel}\n\nTelemetry summary:\n${fieldSummaries}`;
    const result = await model.generateContent(userPrompt);
    const text = result.response.text().trim()
      .replace(/^```json\n?/, '').replace(/\n?```$/, '');
    return JSON.parse(text);
  },
};
